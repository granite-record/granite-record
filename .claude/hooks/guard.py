#!/usr/bin/env python3
# GRANITE_VERSION: 2026-10-26.4
"""
What an AI assistant working in this repository may not do on its own.

The person, 26 October 2026: "make sure ... this development will avoid the
mistakes of other AI agents who have deleted codebases or ones that have
gained unapproved access to the backend of websites it wasn't supposed to."

Claude Code runs this before every tool call it is wired to in
.claude/settings.json (a PreToolUse hook), in every session on every machine
that opens this repository, the person's own included, and in every helper
agent a session starts. It reads the call and answers one of three ways:

  allow  -- nothing here concerns it (almost every call).
  ask    -- it needs the person's word, so Claude Code asks them, whatever
            permission mode the session is in. Publishing, a General Court
            fetch, a change to main, a GitHub merge, the Cloudflare backend.
  deny   -- no assistant should do it at all; the reason says what to do
            instead. Asking the General Court's servers from an ad-hoc
            command, a force push, wiping the untracked data folders,
            rewriting history, overwriting the person's hand-made records.

These are CLAUDE.md's "Never run these without asking" and the hand-made
files rule, enforced rather than only written down. preflight's
_assistant_guard runs decide() over a table of calls that must be stopped
and calls that must not be, so weakening a rule here fails the build;
changing that table, or this file, is a person's decision.

A guard is a backstop, not a sandbox: a determined workaround can get past
any pattern. What it is for is the honest mistake made at speed -- the
`git clean -fdx` that takes 34 GB of captions with it, the second fetch
started while the first still runs, the push to main that goes live tonight.

If this script itself fails, the call is put to the person (ask), never let
through silently and never blocked for good.
"""
import json
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# ---- where the General Court is ---------------------------------------------
# The web server whose firewall has blocked this project twice, its older
# name, and the SQL host whose credentials it publishes (probe_db.HOST).
GC_HOSTS = re.compile(r"(?<![\w-])(?:[\w-]+\.)*(?:gc\.nh\.gov|gencourt\.state\.nh\.us)"
                      r"|(?<![\d.])66\.211\.150\.69(?![\d])", re.I)
# Words that mean a command reaches the network, rather than reading a file
# that happens to name the host (grep "gc.nh.gov" src/ is fine).
NET = re.compile(r"\b(?:curl|wget|Invoke-WebRequest|iwr|Invoke-RestMethod|irm|aria2c|lynx|w3m|"
                 r"links|elinks|httpie|https?\s|nc|ncat|netcat|telnet|s_client|urlopen|urllib|"
                 r"requests\.|httpx|aiohttp|fetch\(|playwright|puppeteer|chromium|goto\(|"
                 r"ping|nslookup|dig|traceroute|tracert|sqlcmd|pyodbc|pymssql|tsql|"
                 r"Test-NetConnection|yt-dlp)\b", re.I)

# ---- scripts that ask the General Court ---------------------------------------
# Named in CLAUDE.md, plus any script that calls refusal.check(), which every
# script carrying a General Court URL does (preflight holds that).
GC_SCRIPT_NAMES = re.compile(
    r"(?:^|/)(?:fetch_[\w-]*|snapshot_gencourt|resolve_members|check_civics_links|"
    r"probe_db|probe_schema|probe_calendars|probe_archive_shape|gc_lane|nightly)\.py$")
NOT_FETCHERS = {"preflight.py", "refusal.py", "cloud.py", "guard.py"}

# ---- folders git does not hold, and the person's own ---------------------------
# Untracked and expensive to get back (.gitignore): the captions, the database
# dump, the fetch archive and its lock, the page caches. Then the person's
# hand-made files and the published record, which git holds but no generator
# may write.
DATA_DIRS = ("work", "db", "archive", "bill_pages", "bill_text", "rc_pages", "status_pages",
             "calendars", "calendars_senate", "member_pages", "nh-archive", "logs", "watchers")
HANDMADE_DIRS = ("corrections", "review")
KEPT_DIRS = ("records", "collected", "generated", "src", "functions", "workers", ".github",
             ".claude", ".git")
# A recursive delete is fine here, and nowhere else without the person.
THROWAWAY = ("site", ".build_cache", "node_modules", "__pycache__", ".pytest_cache",
             ".claude/worktrees", "tmp_site", "scratch")
# The person's measurements, which only review.py appends to.
NEVER_EDIT = {"STATE.md": "STATE.md is generated by src/ops/handoff.py; never edit it",
              "review/ground_truth.csv": "review/ground_truth.csv is 35 proceedings a person timed "
                                         "with a stopwatch; nothing but that person changes it",
              "review/checked.jsonl": "review/checked.jsonl is the bench's judgments, appended "
                                      "only by src/checks/review.py"}

SECRET_WORDS = re.compile(r"(?:TOKEN|SECRET|PASSWORD|PASSWD|API_KEY|APIKEY|ACCESS_KEY|"
                          r"PRIVATE_KEY|CREDENTIAL)", re.I)
SECRET_FILES = re.compile(r"(?:^|[\s/'\"=<])(?:\.dev\.vars|\.env(?:\.[\w-]+)?|\.git-credentials|"
                          r"\.netrc|id_rsa|id_ed25519|[\w-]*\.pem|\.wrangler/config|"
                          r"wrangler/config/default\.toml)(?=$|[\s'\";|&)])", re.I)


def _segments(cmd):
    """The command split into the simple commands a shell would run."""
    return [s.strip() for s in re.split(r"&&|\|\||[;|\n]|\$\(|`", cmd) if s.strip()]


def _words(seg):
    try:
        return shlex.split(seg, posix=True)
    except ValueError:
        return seg.split()


def _rel(p, cwd):
    """A path as the repository names it ("work/x"), or None outside it."""
    p = p.strip("'\"").replace("\\", "/")
    if p.startswith("~"):
        return None
    try:
        full = (Path(cwd) / p).resolve() if not os.path.isabs(p) else Path(p).resolve()
        return full.relative_to(ROOT).as_posix()
    except (ValueError, OSError):
        return None


def _under(rel, dirs):
    return rel is not None and any(rel == d or rel.startswith(d + "/") for d in dirs)


def _dirty(cwd):
    try:
        out = subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"],
                             cwd=cwd, capture_output=True, text=True, encoding="utf-8",
                             errors="replace", timeout=10)
        return bool(out.stdout.strip())
    except (OSError, subprocess.SubprocessError):
        return True


def _branch(cwd):
    try:
        return subprocess.run(["git", "rev-parse", "--abbrev-ref", "HEAD"], cwd=cwd,
                              capture_output=True, text=True, encoding="utf-8",
                              errors="replace", timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


def _git(words):
    """The git subcommand and its arguments, past any -c/-C options."""
    if not words or not re.fullmatch(r"(?:.*/)?git(?:\.exe)?", words[0]):
        return None, []
    i = 1
    while i < len(words) and words[i].startswith("-"):
        i += 2 if words[i] in ("-c", "-C", "--git-dir", "--work-tree") else 1
    return (words[i], words[i + 1:]) if i < len(words) else (None, [])


def _script(words, cwd):
    """The .py file a python command runs, as a Path, or None."""
    if not words or not re.fullmatch(r"(?:.*/)?(?:python3?|py)(?:\.exe)?|(?:.*/)?uv", words[0]):
        return None
    for w in words[1:]:
        if w in ("-c", "-m"):
            return None
        if w.startswith("-"):
            continue
        if w.endswith(".py"):
            p = Path(w.replace("\\", "/"))
            return p if p.is_absolute() else Path(cwd) / p
        return None
    return None


# What starts wrangler: the word itself, or a launcher before it (npx.cmd is
# how PowerShell runs it), past any NAME=value and flags.
LAUNCHERS = {"npx", "npx.cmd", "npx.exe", "bunx", "pnpm", "pnpm.cmd", "yarn", "yarn.cmd", "dlx",
             "exec", "&", "call", "cmd", "cmd.exe", "/c"}


def _wrangler(words):
    """wrangler's own arguments when this segment runs it, else None."""
    for i, w in enumerate(words):
        b = w.rsplit("/", 1)[-1].lower()
        if re.fullmatch(r"wrangler(?:\.cmd|\.exe)?", b):
            return words[i + 1:]
        if b in LAUNCHERS or w.startswith("-") or re.fullmatch(r"[A-Za-z_]\w*=\S*", w):
            continue
        return None
    return None


def _flag(args, long, short):
    """The value of --long X, --long=X, -s X or -s=X, or None."""
    for i, a in enumerate(args):
        for f in (long, short):
            if a == f and i + 1 < len(args):
                return args[i + 1]
            if a.startswith(f + "="):
                return a[len(f) + 1:]
    return None


def _live_wrangler(args, seg, cwd):
    """(decision, reason) for wrangler aimed at the live Worker, or None.
    wrangler dev with its production environment, or --remote, runs the
    Worker's own code against the General Court's database from here, so it
    is denied; a put of control.json is the person's switch, so it asks."""
    conf = _flag(args, "--config", "-c")
    live = (conf is not None and re.search(r"(?:^|/)workers/live(?:/|$)", conf.replace("\\", "/"))) or (
        conf is None and _under(_rel(".", cwd), ("workers/live",)))
    env = _flag(args, "--env", "-e")
    real = (env or "").strip("'\"") == "production" or "--remote" in args or re.search(
        r"\bCLOUDFLARE_ENV=['\"]?production\b", seg)
    sub = next((a for a in args if not a.startswith("-")), None)
    if sub == "dev" and live and real:
        return "deny", ("wrangler dev with the live Worker's production environment, or --remote, "
                        "runs it from here against the General Court's database, the host only "
                        "production may name (workers/live/DESIGN.md 6.2). Run it at the top level, "
                        "against fake_tds.js on 127.0.0.1, or ask the person.")
    if "graniterecord-live/control.json" in seg and re.search(r"\br2\s+object\s+put\b", seg):
        return "ask", ("this turns the live layer's reads of the General Court's database on or "
                       "off: control.json is the person's one switch (workers/live/README.md).")
    return None


def bash(cmd, cwd):
    """(decision, reason) for a shell command."""
    flat = cmd.replace("\\", "/")
    # 1. The General Court, from any ad-hoc command.
    for seg in _segments(flat) + [flat]:
        if GC_HOSTS.search(seg) and NET.search(seg):
            return "deny", ("this command would contact the General Court's servers "
                            "(gc.nh.gov or its database host). Their firewall has blocked this "
                            "project twice. If a fetch is needed, say so and let the person start "
                            "it (CLAUDE.md, 'Never run these without asking').")
    for seg in _segments(flat):
        words = _words(seg)
        if not words:
            continue
        head = words[0].rsplit("/", 1)[-1].lower()
        sub, args = _git(words)
        argstr = " ".join(args)

        # 2. Git: what cannot be undone, and what goes live.
        if sub == "push":
            if any(a in ("--force", "-f", "--mirror") or re.fullmatch(r"-\w*f\w*", a) and not
                   a.startswith("--") for a in args) or any(a.startswith("+") for a in args):
                return "deny", ("a force push rewrites what others have; push a new commit "
                                "instead (a merge, or a revert).")
            if "--delete" in args or "-d" in args or any(re.match(r"^:\S", a) for a in args):
                return "ask", "this deletes a branch on GitHub."
            refs = [a for a in args if not a.startswith("-")]
            dests = [r.split(":", 1)[-1] for r in refs[1:]] if len(refs) > 1 else []
            if any(re.fullmatch(r"(?:refs/heads/)?(?:main|master)", d) for d in dests) or (
                    not dests and _branch(cwd) in ("main", "master")):
                return "ask", ("this changes main, which is the live site: the nightly publishes "
                               "it. main changes only on the person's word.")
            if any(a.startswith("--force-with-lease") for a in args) and any(
                    re.search(r"(?:^|:)(?:refs/heads/)?(?:main|master|dev)$", r) for r in refs):
                return "deny", "a force push to main or dev rewrites shared history."
        if sub == "clean" and re.search(r"(?:^|\s)-\w*f|--force", argstr):
            return "deny", ("git clean -f deletes untracked files, and this repository's data is "
                            "untracked: 34 GB of captions in work/, the database dump in db/, the "
                            "fetch archive. Delete named files instead.")
        if sub in ("filter-branch", "filter-repo", "replace") or (
                sub == "reflog" and "expire" in args) or (
                sub == "gc" and "--prune" in argstr) or (sub == "update-ref" and "-d" in args):
            return "deny", "this rewrites or discards git history, which is how work is recovered."
        # The branch named exactly, so ">/dev/null" is not the dev branch.
        if sub == "branch" and re.search(r"(?:^|\s)(?:-D|-d|--delete)\b", argstr) and any(
                re.fullmatch(r"(?:origin/)?(?:main|master|dev)", a) for a in args):
            return "deny", "main and dev are never deleted."
        if sub == "stash" and args[:1] and args[0] in ("drop", "clear"):
            return "ask", "this throws away stashed work."
        if (sub == "reset" and "--hard" in args) or (
                sub == "checkout" and ("-f" in args or "--force" in args or
                                       ("--" in args and "." in args))) or (
                sub == "restore" and "--staged" not in args and "." in args):
            if _dirty(cwd):
                return "deny", ("this would discard uncommitted changes. Commit them, or "
                                "`git stash` them, first.")
        if head in ("gh", "gh.exe") and len(words) > 1:
            rest = " ".join(words[1:])
            if re.match(r"repo\s+delete\b", rest):
                return "deny", "deleting a repository is the person's to do, in GitHub."
            if re.match(r"(?:pr\s+merge|repo\s+(?:edit|rename|archive|transfer)|secret|variable|"
                        r"workflow\s+(?:run|enable|disable)|release\s+delete|auth\s+token|"
                        r"ruleset)\b", rest) or (re.match(r"api\b", rest) and re.search(
                            r"(?:-X|--method)\s*(?:PUT|PATCH|DELETE|POST)", rest, re.I)):
                return "ask", "this changes the repository's settings, secrets or main on GitHub."

        # 3. Deleting things.
        recursive = (head in ("rm", "rm.exe") and any(
            re.fullmatch(r"-\w*[rR]\w*|--recursive", w) for w in words[1:])) or (
            head in ("rmdir", "rd") and any(w.lower() == "/s" for w in words[1:])) or (
            head.lower() in ("remove-item", "ri", "del", "erase") and any(
                w.lower().startswith("-r") for w in words[1:])) or (
            "shutil.rmtree" in seg) or (head == "find" and ("-delete" in words or
                                                            re.search(r"-exec\s+rm\b", seg)))
        if head in ("rm", "rm.exe", "rmdir", "rd", "remove-item", "ri", "del", "erase", "unlink",
                    "find") or "shutil.rmtree" in seg:
            targets = [w for w in words[1:] if not w.startswith("-") and not w.startswith("/s")]
            if head == "find":
                targets = [w for w in words[1:2] if not w.startswith("-")]
            for t in targets or ["."]:
                rel = _rel(t, cwd)
                temp = re.match(r"(?:/tmp/|\$TMPDIR|\$\{TMPDIR|/var/tmp/|%TEMP%|\$env:TEMP)", t)
                if temp:
                    continue
                if rel is None and not os.path.isabs(t.strip("'\"")) and not t.startswith("~"):
                    rel = t
                if _under(rel, DATA_DIRS):
                    return "deny", (f"{t} is data git does not hold and cannot give back "
                                    "(captions, the database dump, the fetch archive). Ask the "
                                    "person.")
                if _under(rel, HANDMADE_DIRS):
                    return "ask", f"{t} is in the person's own hand-made files."
                if recursive and not _under(rel, THROWAWAY):
                    if rel in ("", ".", "./", "*", "/", "..") or rel is None or "*" in str(rel) \
                            or "$" in str(rel) or _under(rel, KEPT_DIRS):
                        return "deny", (f"a recursive delete of {t} reaches the repository, its "
                                        "history or somewhere it cannot see the end of. Only "
                                        "the throwaway folders (site/, .build_cache/, "
                                        ".claude/worktrees/, /tmp) are deleted whole.")
                    return "ask", (f"a recursive delete of {t}, outside the throwaway folders "
                                   "(site/, .build_cache/, .claude/worktrees/, /tmp).")
        # Overwriting the person's files through the shell.
        for m in re.finditer(r"(?<![>&\d])>(?!>)\s*([^\s;|&]+)", seg):
            rel = _rel(m.group(1), cwd)
            if _under(rel, HANDMADE_DIRS) or rel in NEVER_EDIT:
                return "deny", (f"this overwrites {m.group(1)}, one of the person's hand-made "
                                "files or a generated file nobody edits. Use the Edit tool for a "
                                "change the person asked for.")

        # 4. Publishing and the backend.
        if head in ("publish", "publish.bat", "publish.cmd") or re.search(
                r"(?:^|\s|/)publish\.bat\b", seg):
            return "ask", "publish deploys the live site from this machine."
        wargs = _wrangler(words)
        if wargs is not None or re.search(r"\b(?:npx|bunx|pnpm\s+dlx)\s+wrangler", seg):
            said = _live_wrangler(wargs or [], seg, cwd)
            if said:
                return said
            return "ask", ("wrangler reaches the Cloudflare account: the live site, the D1 "
                           "database of followers' emails, the R2 bucket, the Workers.")
        if re.search(r"api\.cloudflare\.com|\.r2\.cloudflarestorage\.com", seg):
            return "ask", "this reaches the Cloudflare account directly."
        if SECRET_FILES.search(seg) or re.search(r"\$\{?\w*" + SECRET_WORDS.pattern, seg, re.I) \
                or head in ("printenv", "env", "set") and len(words) == 1:
            return "ask", ("this would read a credential (a token, key or password). No secret "
                           "is ever printed or tracked here.")

        # 5. Scripts that ask the General Court, or change what is live.
        script = _script(words, cwd)
        if script is not None:
            name = script.name
            body = ""
            try:
                body = script.read_text(encoding="utf-8", errors="replace")
            except OSError:
                pass
            if name == "refusal.py" and re.search(r"--clear|--stand-down", seg):
                return "ask", ("clearing a refusal, or standing the laptop down, is the person's "
                               "decision (CLAUDE.md).")
            if name == "cloud.py" and re.search(r"\b(?:push|seed-kit|state-up)\b", seg):
                return "ask", "this changes the private bucket the nightly builds from."
            if name == "build_all.py" and not re.search(r"--local|--dry-run", seg):
                return "ask", ("build_all.py without --local runs its network steps, which ask "
                               "the General Court. Add --local, or ask the person.")
            if name not in NOT_FETCHERS and (GC_SCRIPT_NAMES.search(script.as_posix()) or
                                             "refusal.check(" in body):
                return "ask", (f"{name} asks the General Court's servers. CLAUDE.md: never run "
                               "it without asking, and never two at once -- check archive/.lock "
                               "and watchers/README.md first.")
    return "allow", ""


def edit(tool, path, cwd):
    rel = _rel(path, cwd)
    if rel in NEVER_EDIT:
        return "deny", NEVER_EDIT[rel] + "."
    if tool == "Write" and _under(rel, HANDMADE_DIRS) and (ROOT / rel).exists():
        return "ask", (f"{rel} is one of the person's hand-made files; writing it whole replaces "
                       "everything in it. Use Edit for the change the person asked for.")
    if rel in (".claude/settings.json",) or _under(rel, (".claude/hooks",)):
        return "ask", ("this changes the guard on what an assistant may do here, which is the "
                       "person's to change.")
    if _under(rel, (".github/workflows",)):
        return "ask", "the workflows build and deploy the live site every night."
    return "allow", ""


def web(url):
    if GC_HOSTS.search(url or ""):
        return "deny", ("never fetch a General Court page: their firewall has blocked this "
                        "project twice. Ask the person to print the page.")
    if re.search(r"api\.cloudflare\.com|cloudflarestorage\.com", url or ""):
        return "deny", "the Cloudflare account is not an assistant's to reach."
    return "allow", ""


GITHUB_ASK = {"merge_pull_request": "merging goes to main, the live site, on the person's word",
              "delete_file": "this deletes a file on GitHub",
              "actions_run_trigger": "this starts a GitHub workflow, which can deploy the site",
              "create_repository": "this creates a repository", "fork_repository": "this forks"}


def decide(tool, inp, cwd=None):
    """(decision, reason) for one tool call: "allow", "ask" or "deny"."""
    cwd = cwd or str(ROOT)
    inp = inp or {}
    if tool in ("Bash", "PowerShell"):
        return bash(inp.get("command", ""), cwd)
    if tool in ("Edit", "Write", "MultiEdit", "NotebookEdit"):
        return edit(tool, inp.get("file_path") or inp.get("notebook_path") or "", cwd)
    if tool == "WebFetch":
        return web(inp.get("url", ""))
    if tool.startswith("mcp__github__"):
        op = tool[len("mcp__github__"):]
        if op in GITHUB_ASK:
            return "ask", GITHUB_ASK[op] + "."
        if op in ("create_or_update_file", "push_files") and str(
                inp.get("branch", "")).lower() in ("main", "master"):
            return "ask", "this writes straight to main, the live site."
    return "allow", ""


def main():
    try:
        call = json.load(sys.stdin)
        decision, reason = decide(call.get("tool_name", ""), call.get("tool_input") or {},
                                  call.get("cwd"))
    except Exception as e:                       # noqa: BLE001 -- put it to the person
        decision, reason = "ask", f"the repository's guard could not read this call ({e})"
    if decision == "allow":
        return 0
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse", "permissionDecision": decision,
        "permissionDecisionReason": "Granite Record guard (.claude/hooks/guard.py): " + reason}}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
